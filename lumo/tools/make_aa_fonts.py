"""Build lumo/esp32_client/aa_fonts.h: smooth (anti-aliased) Inter glyphs for
the premium clock faces.

Adafruit GFX only draws 1-bit fonts, which is what made the old clock look
blocky. Here each glyph is rendered at 4x, scaled down to the panel's real
pixels and stored as 4-bit coverage, so the firmware can blend it onto any
background. The big Nightstand digits also carry a soft glow, stored at half
resolution because it is a blur anyway.

Run from the repo root (needs Pillow and the Inter fonts):
    python3 lumo/tools/make_aa_fonts.py [path/to/inter/fonts]

Inter is under the SIL Open Font License 1.1 (rsms.me/inter).
"""
import os, sys
from PIL import Image, ImageDraw, ImageFont, ImageFilter

FONT_DIR = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/opentype/inter"
OUT = os.path.join(os.path.dirname(__file__), "..", "esp32_client", "aa_fonts.h")
SS = 4
DEG = "\x7f"       # '°' lives in the DEL slot so strings stay plain ASCII
ASCII = "".join(chr(c) for c in range(32, 127)) + DEG
CAPS = " 0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ:"
DIGITS = "0123456789:"

# name, file, pixel size, characters, glow radius (0 = none)
FONTS = [
    ("AA_MONO_TIME",  "InterDisplay-ExtraLight.otf", 104, DIGITS, 0),
    ("AA_STACK_TIME", "InterDisplay-SemiBold.otf",    98, DIGITS, 0),
    ("AA_NIGHT_TIME", "InterDisplay-Thin.otf",       112, DIGITS, 7),
    ("AA_CAPS9",      "Inter-SemiBold.otf",            9, CAPS,   0),
    ("AA_BODY11",     "Inter-Regular.otf",            11, ASCII,  0),
    ("AA_SEMI11",     "Inter-SemiBold.otf",           11, ASCII,  0),
    ("AA_DISP14",     "InterDisplay-Medium.otf",      14, ASCII,  0),
    ("AA_DISP20",     "InterDisplay-Medium.otf",      20, ASCII,  0),
]


def render(font, ch):
    """Coverage of one glyph at panel size: (alpha image, left, top, advance),
    with left/top relative to the pen position on the baseline."""
    c = "°" if ch == DEG else ch
    size = font.size
    pad = size // 2 + 8
    big = Image.new("L", ((size * 2 + pad * 2) * SS, (size * 2 + pad * 2) * SS), 0)
    ox, oy = pad * SS, (size + pad) * SS          # pen position, on the baseline
    ImageDraw.Draw(big).text((ox, oy), c, font=font, fill=255, anchor="ls")
    small = big.reduce(SS)                        # box filter: true coverage
    adv = font.getlength(c) / SS
    box = small.getbbox()
    if not box:
        return None, 0, 0, adv
    img = small.crop(box)
    return img, box[0] - pad, box[1] - (size + pad), adv


def nibbles(values):
    out = bytearray()
    for i in range(0, len(values), 2):
        hi = values[i]
        lo = values[i + 1] if i + 1 < len(values) else 0
        out.append((hi << 4) | lo)
    return out


def q4(v):
    return min(15, (v * 15 + 127) // 255)


def build(name, path, px, chars, glow):
    font = ImageFont.truetype(os.path.join(FONT_DIR, path), px * SS)
    bits = bytearray()
    gbits = bytearray()
    rows = []
    grows = []
    top = 0
    for ch in chars:
        img, left, ytop, adv = render(font, ch)
        if img is None:
            rows.append((len(bits), 0, 0, 0, 0, round(adv)))
            grows.append((len(gbits), 0, 0))
            continue
        w, h = img.size
        top = min(top, ytop)
        rows.append((len(bits), w, h, left, ytop, round(adv)))
        bits += nibbles([q4(v) for v in img.tobytes()])
        if glow:
            # the glow covers the glyph plus 2*radius on every side, at half size
            p = glow * 2
            base = Image.new("L", (w + 2 * p, h + 2 * p), 0)
            base.paste(img, (p, p))
            halo = base.filter(ImageFilter.GaussianBlur(glow))
            gw, gh = (halo.width + 1) // 2, (halo.height + 1) // 2
            halo = halo.resize((gw, gh), Image.BOX)
            grows.append((len(gbits), gw, gh))
            gbits += nibbles([q4(v) for v in halo.tobytes()])
    descent = max((r[4] + r[2] for r in rows if r[2]), default=0)
    return rows, bits, grows, gbits, -top, descent


def c_bytes(data):
    lines = []
    for i in range(0, len(data), 24):
        lines.append("  " + ", ".join(f"0x{b:02X}" for b in data[i:i + 24]) + ",")
    return "\n".join(lines)


def c_chars(chars):
    return "".join("\\x7F" if c == DEG else ("\\\\" if c == "\\" else ('\\"' if c == '"' else c)) for c in chars)


out = ["// Generated by lumo/tools/make_aa_fonts.py: do not edit by hand.",
       "// Inter by Rasmus Andersson, SIL Open Font License 1.1.",
       "#pragma once", "#include \"aa_text.h\"", ""]
total = 0
for name, path, px, chars, glow in FONTS:
    rows, bits, grows, gbits, ascent, descent = build(name, path, px, chars, glow)
    low = name.lower()
    total += len(bits) + len(gbits)
    out.append(f"// {path} {px}px: {len(chars)} glyphs, {len(bits) + len(gbits)} bytes")
    out.append(f"static const uint8_t {low}_bits[] PROGMEM = {{\n{c_bytes(bits)}\n}};")
    out.append(f"static const AAGlyph {low}_glyphs[] PROGMEM = {{")
    for r in rows:
        out.append("  {%d, %d, %d, %d, %d, %d}," % r)
    out.append("};")
    if glow:
        out.append(f"static const uint8_t {low}_glow[] PROGMEM = {{\n{c_bytes(gbits)}\n}};")
        out.append(f"static const AAGlowGlyph {low}_glows[] PROGMEM = {{")
        for r in grows:
            out.append("  {%d, %d, %d}," % r)
        out.append("};")
    g = f"{low}_glow, {low}_glows, {glow * 2}" if glow else "nullptr, nullptr, 0"
    out.append(f'static const AAFont {name} = {{ {low}_bits, {low}_glyphs, "{c_chars(chars)}", {len(chars)}, {ascent}, {descent}, {g} }};')
    out.append("")
open(OUT, "w").write("\n".join(out))
print(f"wrote {os.path.normpath(OUT)}: {total} bytes of glyph data")
